-- ---- Vista de saldos ----
CREATE OR REPLACE VIEW vw_grupo_saldos AS
WITH pagado AS (
    SELECT grupo_id, pagado_por AS user_id, COALESCE(SUM(monto), 0) AS total_pagado
    FROM grupo_gastos WHERE estado = 'activo'
    GROUP BY grupo_id, pagado_por
),
asignado AS (
    SELECT g.grupo_id, p.user_id, COALESCE(SUM(p.monto_asignado), 0) AS total_asignado
    FROM grupo_gasto_participantes p
    JOIN grupo_gastos g ON g.id = p.gasto_id
    WHERE g.estado = 'activo'
    GROUP BY g.grupo_id, p.user_id
),
liq_enviado AS (
    SELECT grupo_id, de_user_id AS user_id, COALESCE(SUM(monto), 0) AS total_liquidado_enviado
    FROM grupo_liquidaciones WHERE estado = 'confirmada'
    GROUP BY grupo_id, de_user_id
),
liq_recibido AS (
    SELECT grupo_id, para_user_id AS user_id, COALESCE(SUM(monto), 0) AS total_liquidado_recibido
    FROM grupo_liquidaciones WHERE estado = 'confirmada'
    GROUP BY grupo_id, para_user_id
),
miembros AS (
    SELECT grupo_id, user_id FROM grupo_miembros WHERE estado = 'activo'
)
SELECT
    m.grupo_id,
    m.user_id,
    COALESCE(p.total_pagado, 0)              AS pagado,
    COALESCE(a.total_asignado, 0)            AS asignado,
    COALESCE(le.total_liquidado_enviado, 0)  AS liquidado_enviado,
    COALESCE(lr.total_liquidado_recibido, 0) AS liquidado_recibido,
    (
        COALESCE(p.total_pagado, 0)
        - COALESCE(a.total_asignado, 0)
        + COALESCE(le.total_liquidado_enviado, 0)
        - COALESCE(lr.total_liquidado_recibido, 0)
    ) AS saldo_neto
FROM miembros m
LEFT JOIN pagado        p  ON p.grupo_id  = m.grupo_id AND p.user_id  = m.user_id
LEFT JOIN asignado      a  ON a.grupo_id  = m.grupo_id AND a.user_id  = m.user_id
LEFT JOIN liq_enviado   le ON le.grupo_id = m.grupo_id AND le.user_id = m.user_id
LEFT JOIN liq_recibido  lr ON lr.grupo_id = m.grupo_id AND lr.user_id = m.user_id;

-- ---- RPC: crear_grupo_gasto_compartido ----
-- Crea un grupo usando el auth.uid() del caller y devuelve el ID creado.
-- SECURITY DEFINER evita depender del INSERT directo por PostgREST/RLS.
CREATE OR REPLACE FUNCTION crear_grupo_gasto_compartido(
    p_nombre VARCHAR,
    p_descripcion TEXT DEFAULT NULL,
    p_moneda VARCHAR DEFAULT 'ARS'
)
RETURNS BIGINT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_user_id UUID;
    v_grupo_id BIGINT;
BEGIN
    v_user_id := auth.uid();

    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'No autenticado';
    END IF;

    INSERT INTO grupos_gastos (nombre, descripcion, moneda, creado_por)
    VALUES (TRIM(p_nombre), NULLIF(TRIM(COALESCE(p_descripcion, '')), ''), COALESCE(p_moneda, 'ARS'), v_user_id)
    RETURNING id INTO v_grupo_id;

    RETURN v_grupo_id;
END;
$$;

REVOKE ALL ON FUNCTION crear_grupo_gasto_compartido(VARCHAR, TEXT, VARCHAR) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION crear_grupo_gasto_compartido(VARCHAR, TEXT, VARCHAR) TO authenticated;

-- ---- RPC: aceptar_invitacion_grupo ----
-- Transacción atómica: marca invitación aceptada + inserta miembro activo.
-- Invocada por backend Express con service role.
CREATE OR REPLACE FUNCTION aceptar_invitacion_grupo(p_token UUID, p_user_id UUID)
RETURNS BIGINT
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_grupo_id BIGINT;
BEGIN
    UPDATE grupo_invitaciones
       SET estado = 'aceptada', fecha_resolucion = NOW()
     WHERE token = p_token AND estado = 'pendiente'
     RETURNING grupo_id INTO v_grupo_id;

    IF v_grupo_id IS NULL THEN
        RAISE EXCEPTION 'Invitacion invalida o ya resuelta';
    END IF;

    INSERT INTO grupo_miembros (grupo_id, user_id, rol, estado)
    VALUES (v_grupo_id, p_user_id, 'miembro', 'activo')
    ON CONFLICT (grupo_id, user_id) DO UPDATE
        SET estado = 'activo', fecha_baja = NULL;

    RETURN v_grupo_id;
END;
$$;

REVOKE ALL ON FUNCTION aceptar_invitacion_grupo(UUID, UUID) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION aceptar_invitacion_grupo(UUID, UUID) TO authenticated;
