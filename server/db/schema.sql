-- Políticas de acceso para Categorías:
-- Las categorías con user_id = NULL son globales (visibles para todos, no modificables).
-- Las categorías con user_id = auth.uid() son propias del usuario (creadas/eliminadas por él).
-- MIGRACIÓN requerida antes de aplicar estas políticas:
--   ALTER TABLE categorias ADD COLUMN IF NOT EXISTS user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE;
--   DROP POLICY IF EXISTS "Allow select categories for all users" ON categorias;
--   DROP POLICY IF EXISTS "Prevent insert categories" ON categorias;
--   DROP POLICY IF EXISTS "Prevent update categories" ON categorias;
--   DROP POLICY IF EXISTS "Prevent delete categories" ON categorias;
CREATE POLICY "categorias_select" ON categorias FOR SELECT USING (user_id IS NULL OR auth.uid() = user_id);
CREATE POLICY "categorias_insert" ON categorias FOR INSERT WITH CHECK (auth.uid() = user_id);
CREATE POLICY "categorias_delete" ON categorias FOR DELETE USING (auth.uid() = user_id);

