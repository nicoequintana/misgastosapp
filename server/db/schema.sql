-- FASE 1: SISTEMA DE NOTIFICACIONES
-- ============================================

-- Tabla de Notificaciones
-- Almacena todas las notificaciones del usuario con soporte de email.
CREATE TABLE IF NOT EXISTS notificaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    titulo TEXT NOT NULL,
    mensaje TEXT NOT NULL,
    tipo VARCHAR(20) NOT NULL DEFAULT 'info',
    -- Tipos válidos: info | success | warning | error
    leida BOOLEAN NOT NULL DEFAULT FALSE,
    origen VARCHAR(30) NOT NULL DEFAULT 'app',
    -- Orígenes válidos: app | gastos | ingresos | n8n | whatsapp | sistema | resumen | proyeccion
    metadata JSONB,
    email_enviado BOOLEAN NOT NULL DEFAULT FALSE,
    email_error TEXT,
    fecha_creacion TIMESTAMPTZ DEFAULT NOW()
);

-- Tabla de Configuración de Notificaciones por Usuario
-- Permite controlar qué notificaciones recibe el usuario y si se envían por email.
CREATE TABLE IF NOT EXISTS configuracion_notificaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    -- Configuración general de email
    email_habilitado BOOLEAN NOT NULL DEFAULT FALSE,
    email_saldo_bajo BOOLEAN NOT NULL DEFAULT FALSE,
    email_gasto_alto BOOLEAN NOT NULL DEFAULT FALSE,
    email_resumen_diario BOOLEAN NOT NULL DEFAULT FALSE,
    email_resumen_semanal BOOLEAN NOT NULL DEFAULT FALSE,
    email_resumen_mensual BOOLEAN NOT NULL DEFAULT FALSE,
    email_notificaciones_n8n BOOLEAN NOT NULL DEFAULT TRUE,
    -- Configuración de alertas financieras
    notificar_saldo_bajo BOOLEAN NOT NULL DEFAULT TRUE,
    umbral_saldo_bajo DECIMAL(12,2) DEFAULT 5000,
    notificar_porcentaje_ingreso BOOLEAN NOT NULL DEFAULT TRUE,
    porcentaje_maximo_ingreso DECIMAL(5,2) DEFAULT 80,
    notificar_gasto_alto BOOLEAN NOT NULL DEFAULT TRUE,
    monto_gasto_alto DECIMAL(12,2) DEFAULT 10000,
    fecha_actualizacion TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT configuracion_notificaciones_user_id_unique UNIQUE(user_id)
);

-- RLS para notificaciones
ALTER TABLE notificaciones ENABLE ROW LEVEL SECURITY;
ALTER TABLE configuracion_notificaciones ENABLE ROW LEVEL SECURITY;

CREATE POLICY "notificaciones_select" ON notificaciones FOR SELECT USING (auth.uid() = user_id);
CREATE POLICY "notificaciones_insert" ON notificaciones FOR INSERT WITH CHECK (auth.uid() = user_id);
CREATE POLICY "notificaciones_update" ON notificaciones FOR UPDATE USING (auth.uid() = user_id);
CREATE POLICY "notificaciones_delete" ON notificaciones FOR DELETE USING (auth.uid() = user_id);

CREATE POLICY "config_notif_select" ON configuracion_notificaciones FOR SELECT USING (auth.uid() = user_id);
CREATE POLICY "config_notif_insert" ON configuracion_notificaciones FOR INSERT WITH CHECK (auth.uid() = user_id);
CREATE POLICY "config_notif_update" ON configuracion_notificaciones FOR UPDATE USING (auth.uid() = user_id);

-- Índices para optimizar consultas de notificaciones
CREATE INDEX idx_notificaciones_user_id ON notificaciones(user_id);
CREATE INDEX idx_notificaciones_leida ON notificaciones(user_id, leida);
CREATE INDEX idx_notificaciones_fecha ON notificaciones(user_id, fecha_creacion DESC);
CREATE INDEX idx_config_notif_user_id ON configuracion_notificaciones(user_id);

