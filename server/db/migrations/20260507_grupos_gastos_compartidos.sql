-- SECCIÓN 4: ROW LEVEL SECURITY
-- Habilitar RLS en las 6 tablas nuevas.
-- ============================================================

ALTER TABLE grupos_gastos             ENABLE ROW LEVEL SECURITY;
ALTER TABLE grupo_miembros            ENABLE ROW LEVEL SECURITY;
ALTER TABLE grupo_invitaciones        ENABLE ROW LEVEL SECURITY;
ALTER TABLE grupo_gastos              ENABLE ROW LEVEL SECURITY;
ALTER TABLE grupo_gasto_participantes ENABLE ROW LEVEL SECURITY;
ALTER TABLE grupo_liquidaciones       ENABLE ROW LEVEL SECURITY;

-- ============================================================
-- SECCIÓN 5: POLÍTICAS RLS POR TABLA
-- ============================================================

-- --- grupos_gastos ---
-- SELECT: solo miembros activos del grupo pueden verlo.
CREATE POLICY "grupos_select" ON grupos_gastos
    FOR SELECT USING (is_group_member(id, auth.uid()));
-- INSERT: el usuario que crea el grupo debe declararse como creador.
CREATE POLICY "grupos_insert" ON grupos_gastos
    FOR INSERT WITH CHECK (auth.uid() = creado_por);
-- UPDATE: solo admins del grupo pueden modificarlo (ej. archivar, renombrar).
CREATE POLICY "grupos_update" ON grupos_gastos
    FOR UPDATE USING (is_group_admin(id, auth.uid()));
-- DELETE: solo admins pueden eliminar (eliminación física, aunque en práctica se archiva).
CREATE POLICY "grupos_delete" ON grupos_gastos
    FOR DELETE USING (is_group_admin(id, auth.uid()));

-- --- grupo_miembros ---
-- SELECT: el propio usuario siempre ve su membresía; miembros activos ven al resto.
CREATE POLICY "miembros_select" ON grupo_miembros
    FOR SELECT USING (
        user_id = auth.uid() OR is_group_member(grupo_id, auth.uid())
    );
-- INSERT: solo admins pueden agregar miembros.
CREATE POLICY "miembros_insert_admin" ON grupo_miembros
    FOR INSERT WITH CHECK (
        is_group_admin(grupo_id, auth.uid())
        OR (auth.uid() = user_id AND is_group_creator(grupo_id, auth.uid()))
    );
-- UPDATE: solo admins pueden cambiar rol o estado (remover miembro = soft update).
CREATE POLICY "miembros_update_admin" ON grupo_miembros
    FOR UPDATE USING (is_group_admin(grupo_id, auth.uid()));
-- DELETE no se usa: bajas son soft (estado='removido').

-- --- grupo_invitaciones ---
-- SELECT para admins: ven todas las invitaciones del grupo.
CREATE POLICY "invitaciones_select_admin" ON grupo_invitaciones
    FOR SELECT USING (is_group_admin(grupo_id, auth.uid()));
-- SELECT para invitado: solo puede ver su propia invitación (por email del JWT).
CREATE POLICY "invitaciones_select_invitado" ON grupo_invitaciones
    FOR SELECT USING (
        LOWER(email_invitado) = LOWER(COALESCE(auth.jwt() ->> 'email', ''))
    );
-- INSERT: solo admins pueden crear invitaciones.
CREATE POLICY "invitaciones_insert_admin" ON grupo_invitaciones
    FOR INSERT WITH CHECK (is_group_admin(grupo_id, auth.uid()));
-- UPDATE: el invitado puede aceptar/rechazar; el admin puede cancelar.
CREATE POLICY "invitaciones_update_invitado" ON grupo_invitaciones
    FOR UPDATE USING (
        LOWER(email_invitado) = LOWER(COALESCE(auth.jwt() ->> 'email', ''))
        OR is_group_admin(grupo_id, auth.uid())
    );

-- --- grupo_gastos ---
-- SELECT: cualquier miembro activo puede ver los gastos del grupo.
CREATE POLICY "gastos_select" ON grupo_gastos
    FOR SELECT USING (is_group_member(grupo_id, auth.uid()));
-- INSERT: miembro activo puede cargar gastos, y debe declararse como creador.
CREATE POLICY "gastos_insert" ON grupo_gastos
    FOR INSERT WITH CHECK (
        is_group_member(grupo_id, auth.uid())
        AND creado_por = auth.uid()
    );
-- UPDATE: el creador o un admin puede modificar/anular (soft delete).
CREATE POLICY "gastos_update" ON grupo_gastos
    FOR UPDATE USING (
        is_group_member(grupo_id, auth.uid())
        AND (creado_por = auth.uid() OR is_group_admin(grupo_id, auth.uid()))
    );
-- DELETE no se usa: anulación es soft (estado='anulado').

-- --- grupo_gasto_participantes ---
-- SELECT: miembro activo del grupo padre puede ver los participantes.
CREATE POLICY "participantes_select" ON grupo_gasto_participantes
    FOR SELECT USING (
        EXISTS (
            SELECT 1 FROM grupo_gastos g
            WHERE g.id = gasto_id
              AND is_group_member(g.grupo_id, auth.uid())
        )
    );
-- INSERT: solo quien creó el gasto puede asignar participantes.
CREATE POLICY "participantes_insert" ON grupo_gasto_participantes
    FOR INSERT WITH CHECK (
        EXISTS (
            SELECT 1 FROM grupo_gastos g
            WHERE g.id = gasto_id
              AND is_group_member(g.grupo_id, auth.uid())
              AND g.creado_por = auth.uid()
        )
    );
-- UPDATE/DELETE: no permitidos directos; se reescriben al anular el gasto (soft).

-- --- grupo_liquidaciones ---
-- SELECT: cualquier miembro activo puede ver las liquidaciones del grupo.
CREATE POLICY "liquidaciones_select" ON grupo_liquidaciones
    FOR SELECT USING (is_group_member(grupo_id, auth.uid()));
-- INSERT: miembro activo puede registrar liquidaciones donde sea parte o sea admin.
CREATE POLICY "liquidaciones_insert" ON grupo_liquidaciones
    FOR INSERT WITH CHECK (
        is_group_member(grupo_id, auth.uid())
        AND registrado_por = auth.uid()
        AND (
            de_user_id = auth.uid()
            OR para_user_id = auth.uid()
            OR is_group_admin(grupo_id, auth.uid())
        )
    );
-- UPDATE: quien la registró o un admin puede anularla (soft delete).
CREATE POLICY "liquidaciones_update" ON grupo_liquidaciones
    FOR UPDATE USING (
        is_group_member(grupo_id, auth.uid())
        AND (registrado_por = auth.uid() OR is_group_admin(grupo_id, auth.uid()))
    );

-- ============================================================
-- SECCIÓN 6: VISTA vw_grupo_saldos
-- Calcula el saldo neto de cada miembro activo por grupo.
-- La lógica JS en el frontend (calcularTransferencias) consume esta vista
-- para generar el mínimo set de transferencias necesarias.
--
-- Fórmula del saldo neto:
--   pagado + liquidado_enviado - asignado - liquidado_recibido
--   positivo = a favor (le deben), negativo = en contra (debe)
-- ============================================================

CREATE OR REPLACE VIEW vw_grupo_saldos AS
WITH pagado AS (
    -- Total que cada usuario pagó en gastos activos del grupo
    SELECT grupo_id, pagado_por AS user_id, COALESCE(SUM(monto), 0) AS total_pagado
    FROM grupo_gastos
    WHERE estado = 'activo'
    GROUP BY grupo_id, pagado_por
),
asignado AS (
    -- Total asignado a cada usuario en gastos activos del grupo
    SELECT g.grupo_id, p.user_id, COALESCE(SUM(p.monto_asignado), 0) AS total_asignado
    FROM grupo_gasto_participantes p
    JOIN grupo_gastos g ON g.id = p.gasto_id
    WHERE g.estado = 'activo'
    GROUP BY g.grupo_id, p.user_id
),
liq_enviado AS (
    -- Total de liquidaciones enviadas (pagos que el usuario realizó a otros)
    SELECT grupo_id, de_user_id AS user_id, COALESCE(SUM(monto), 0) AS total_liquidado_enviado
    FROM grupo_liquidaciones
    WHERE estado = 'confirmada'
    GROUP BY grupo_id, de_user_id
),
liq_recibido AS (
    -- Total de liquidaciones recibidas (pagos que otros le realizaron al usuario)
    SELECT grupo_id, para_user_id AS user_id, COALESCE(SUM(monto), 0) AS total_liquidado_recibido
    FROM grupo_liquidaciones
    WHERE estado = 'confirmada'
    GROUP BY grupo_id, para_user_id
),
miembros AS (
    -- Base: solo miembros activos
    SELECT grupo_id, user_id FROM grupo_miembros WHERE estado = 'activo'
)
SELECT
    m.grupo_id,
    m.user_id,
    COALESCE(p.total_pagado, 0)              AS pagado,
    COALESCE(a.total_asignado, 0)            AS asignado,
    COALESCE(le.total_liquidado_enviado, 0)  AS liquidado_enviado,
    COALESCE(lr.total_liquidado_recibido, 0) AS liquidado_recibido,
    -- Saldo neto: positivo = a favor (le deben), negativo = en contra (debe)
    (
        COALESCE(p.total_pagado, 0)
        - COALESCE(a.total_asignado, 0)
        + COALESCE(le.total_liquidado_enviado, 0)
        - COALESCE(lr.total_liquidado_recibido, 0)
    ) AS saldo_neto
FROM miembros m
LEFT JOIN pagado        p  ON p.grupo_id  = m.grupo_id AND p.user_id  = m.user_id
LEFT JOIN asignado      a  ON a.grupo_id  = m.grupo_id AND a.user_id  = m.user_id
LEFT JOIN liq_enviado   le ON le.grupo_id = m.grupo_id AND le.user_id = m.user_id
LEFT JOIN liq_recibido  lr ON lr.grupo_id = m.grupo_id AND lr.user_id = m.user_id;

-- ============================================================
-- SECCIÓN 7: RPC crear_grupo_gasto_compartido
-- Crea un grupo usando auth.uid() y devuelve el ID nuevo.
-- SECURITY DEFINER evita depender del INSERT directo por PostgREST/RLS.
-- ============================================================

CREATE OR REPLACE FUNCTION crear_grupo_gasto_compartido(
    p_nombre VARCHAR,
    p_descripcion TEXT DEFAULT NULL,
    p_moneda VARCHAR DEFAULT 'ARS'
)
RETURNS BIGINT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_user_id UUID;
    v_grupo_id BIGINT;
BEGIN
    v_user_id := auth.uid();

    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'No autenticado';
    END IF;

    INSERT INTO grupos_gastos (nombre, descripcion, moneda, creado_por)
    VALUES (TRIM(p_nombre), NULLIF(TRIM(COALESCE(p_descripcion, '')), ''), COALESCE(p_moneda, 'ARS'), v_user_id)
    RETURNING id INTO v_grupo_id;

    RETURN v_grupo_id;
END;
$$;

REVOKE ALL ON FUNCTION crear_grupo_gasto_compartido(VARCHAR, TEXT, VARCHAR) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION crear_grupo_gasto_compartido(VARCHAR, TEXT, VARCHAR) TO authenticated;

-- ============================================================
-- SECCIÓN 7: RPC aceptar_invitacion_grupo
-- Operación transaccional: marca invitación como aceptada e inserta
-- al usuario como miembro activo en una sola operación atómica.
-- Idempotente: si el miembro ya existe, reactiva su estado a 'activo'.
-- Invocada por el backend Express con service role después de validar JWT.
-- ============================================================

CREATE OR REPLACE FUNCTION aceptar_invitacion_grupo(p_token UUID, p_user_id UUID)
RETURNS BIGINT
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_grupo_id BIGINT;
BEGIN
    -- Marcar invitación como aceptada (solo si está pendiente).
    -- RETURNING garantiza atomicidad: si no hay fila afectada, v_grupo_id queda NULL.
    UPDATE grupo_invitaciones
       SET estado = 'aceptada', fecha_resolucion = NOW()
     WHERE token = p_token AND estado = 'pendiente'
     RETURNING grupo_id INTO v_grupo_id;

    IF v_grupo_id IS NULL THEN
        RAISE EXCEPTION 'Invitacion invalida o ya resuelta';
    END IF;

    -- Insertar miembro activo. Si ya existía (ej. fue removido y re-invitado),
    -- reactivar sin duplicar la fila (ON CONFLICT DO UPDATE).
    INSERT INTO grupo_miembros (grupo_id, user_id, rol, estado)
    VALUES (v_grupo_id, p_user_id, 'miembro', 'activo')
    ON CONFLICT (grupo_id, user_id) DO UPDATE
        SET estado = 'activo', fecha_baja = NULL;

    RETURN v_grupo_id;
END;
$$;

