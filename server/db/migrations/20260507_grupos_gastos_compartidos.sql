-- ============================================================
-- Migración: Grupos de Gastos Compartidos
-- Fecha: 2026-05-07
-- Descripción: Crea el módulo completo de grupos compartidos.
--   - 6 tablas con índices
--   - 2 funciones helper SECURITY DEFINER (is_group_member, is_group_admin)
--   - 2 triggers (updated_at, auto-alta del creador como admin)
--   - RLS habilitado + políticas por tabla
--   - Vista vw_grupo_saldos
--   - RPC aceptar_invitacion_grupo
-- Ejecutar en Supabase SQL Editor de una sola vez.
-- ============================================================

BEGIN;

-- ============================================================
-- SECCIÓN 1: TABLAS E ÍNDICES
-- Orden respeta las FK: grupos_gastos primero, luego las hijas.
-- ============================================================

-- 1.1 grupos_gastos
-- Entidad raíz del módulo. Cada grupo tiene un creador y puede archivarse.
CREATE TABLE IF NOT EXISTS grupos_gastos (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre              VARCHAR(120) NOT NULL,
    descripcion         TEXT,
    creado_por          UUID NOT NULL REFERENCES auth.users(id) ON DELETE RESTRICT,
    moneda              VARCHAR(8)  NOT NULL DEFAULT 'ARS',
    archivado           BOOLEAN     NOT NULL DEFAULT FALSE,
    fecha_creacion      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
-- Índice para listar grupos por creador (admin dashboard)
CREATE INDEX idx_grupos_gastos_creado_por ON grupos_gastos(creado_por);

-- 1.2 grupo_miembros
-- Membresía de un usuario en un grupo. Soft delete via estado='removido'.
CREATE TABLE IF NOT EXISTS grupo_miembros (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grupo_id    BIGINT      NOT NULL REFERENCES grupos_gastos(id) ON DELETE CASCADE,
    user_id     UUID        NOT NULL REFERENCES auth.users(id)    ON DELETE CASCADE,
    rol         VARCHAR(20) NOT NULL DEFAULT 'miembro',
    -- Roles válidos: admin | miembro
    estado      VARCHAR(20) NOT NULL DEFAULT 'activo',
    -- Estados válidos: activo | removido
    alias       VARCHAR(80),
    fecha_alta  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_baja  TIMESTAMPTZ,
    CONSTRAINT grupo_miembros_unique     UNIQUE(grupo_id, user_id),
    CONSTRAINT grupo_miembros_rol_chk   CHECK (rol    IN ('admin','miembro')),
    CONSTRAINT grupo_miembros_estado_chk CHECK (estado IN ('activo','removido'))
);
CREATE INDEX idx_grupo_miembros_grupo       ON grupo_miembros(grupo_id);
CREATE INDEX idx_grupo_miembros_user        ON grupo_miembros(user_id);
-- Índice parcial: acelera búsquedas de miembros activos por usuario
CREATE INDEX idx_grupo_miembros_user_activo ON grupo_miembros(user_id) WHERE estado = 'activo';

-- 1.3 grupo_invitaciones
-- Invitaciones por email con token UUID generado por Supabase.
-- El backend Express solo hace INSERT y lee el token resultante.
CREATE TABLE IF NOT EXISTS grupo_invitaciones (
    id                BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grupo_id          BIGINT      NOT NULL REFERENCES grupos_gastos(id) ON DELETE CASCADE,
    email_invitado    VARCHAR(255) NOT NULL,
    token             UUID        NOT NULL DEFAULT gen_random_uuid(),
    invitado_por      UUID        NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    estado            VARCHAR(20) NOT NULL DEFAULT 'pendiente',
    -- Estados válidos: pendiente | aceptada | rechazada | expirada | cancelada
    fecha_expiracion  TIMESTAMPTZ NOT NULL DEFAULT (NOW() + INTERVAL '7 days'),
    fecha_creacion    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_resolucion  TIMESTAMPTZ,
    CONSTRAINT grupo_invitaciones_token_unique  UNIQUE(token),
    CONSTRAINT grupo_invitaciones_estado_chk   CHECK (estado IN ('pendiente','aceptada','rechazada','expirada','cancelada'))
);
CREATE INDEX idx_grupo_invitaciones_grupo    ON grupo_invitaciones(grupo_id);
-- Índice en email en minúsculas para búsquedas case-insensitive
CREATE INDEX idx_grupo_invitaciones_email    ON grupo_invitaciones(LOWER(email_invitado));
-- Índice parcial: solo invitaciones pendientes (el caso de uso más frecuente)
CREATE INDEX idx_grupo_invitaciones_pendiente ON grupo_invitaciones(grupo_id, estado) WHERE estado = 'pendiente';

-- 1.4 grupo_gastos
-- Gasto cargado dentro de un grupo. Soft delete via estado='anulado'.
-- id_categoria es opcional y referencia las categorías personales/globales del módulo principal.
CREATE TABLE IF NOT EXISTS grupo_gastos (
    id           BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grupo_id     BIGINT       NOT NULL REFERENCES grupos_gastos(id)  ON DELETE CASCADE,
    descripcion  TEXT         NOT NULL,
    monto        DECIMAL(12,2) NOT NULL CHECK (monto > 0),
    moneda       VARCHAR(8)   NOT NULL DEFAULT 'ARS',
    pagado_por   UUID         NOT NULL REFERENCES auth.users(id)     ON DELETE RESTRICT,
    fecha        DATE         NOT NULL DEFAULT CURRENT_DATE,
    nota         TEXT,
    -- Categoría opcional: solo informativa, no afecta saldos del grupo.
    -- Solo se permiten categorías globales (user_id IS NULL) en la UI (ver db.js).
    id_categoria BIGINT       REFERENCES categorias(id)              ON DELETE SET NULL,
    estado       VARCHAR(20)  NOT NULL DEFAULT 'activo',
    -- Estados válidos: activo | anulado
    creado_por   UUID         NOT NULL REFERENCES auth.users(id)     ON DELETE RESTRICT,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    anulado_en   TIMESTAMPTZ,
    anulado_por  UUID         REFERENCES auth.users(id),
    CONSTRAINT grupo_gastos_estado_chk CHECK (estado IN ('activo','anulado'))
);
CREATE INDEX idx_grupo_gastos_grupo   ON grupo_gastos(grupo_id);
CREATE INDEX idx_grupo_gastos_pagador ON grupo_gastos(pagado_por);
-- Índice para listar gastos del grupo por fecha descendente
CREATE INDEX idx_grupo_gastos_fecha   ON grupo_gastos(grupo_id, fecha DESC);
-- Índice parcial: acelera la vista vw_grupo_saldos que filtra por estado='activo'
CREATE INDEX idx_grupo_gastos_activos ON grupo_gastos(grupo_id) WHERE estado = 'activo';

-- 1.5 grupo_gasto_participantes
-- Porción del gasto asignada a cada participante. monto_asignado se persiste
-- calculado al insertar para evitar recalcular siempre y permitir porcentajes
-- custom en el futuro.
CREATE TABLE IF NOT EXISTS grupo_gasto_participantes (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gasto_id        BIGINT       NOT NULL REFERENCES grupo_gastos(id) ON DELETE CASCADE,
    user_id         UUID         NOT NULL REFERENCES auth.users(id)   ON DELETE RESTRICT,
    -- Preparado para porcentajes futuros; en MVP siempre se calcula igualitariamente en db.js
    porcentaje      DECIMAL(7,4),
    monto_asignado  DECIMAL(12,2) NOT NULL CHECK (monto_asignado >= 0),
    fecha_creacion  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT grupo_gasto_participantes_unique UNIQUE(gasto_id, user_id)
);
CREATE INDEX idx_grupo_gasto_participantes_gasto ON grupo_gasto_participantes(gasto_id);
CREATE INDEX idx_grupo_gasto_participantes_user  ON grupo_gasto_participantes(user_id);

-- 1.6 grupo_liquidaciones
-- Registra pagos directos entre miembros que reducen deudas. Soft delete via estado='anulada'.
CREATE TABLE IF NOT EXISTS grupo_liquidaciones (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grupo_id      BIGINT       NOT NULL REFERENCES grupos_gastos(id) ON DELETE CASCADE,
    de_user_id    UUID         NOT NULL REFERENCES auth.users(id)    ON DELETE RESTRICT,
    para_user_id  UUID         NOT NULL REFERENCES auth.users(id)    ON DELETE RESTRICT,
    monto         DECIMAL(12,2) NOT NULL CHECK (monto > 0),
    fecha         DATE         NOT NULL DEFAULT CURRENT_DATE,
    nota          TEXT,
    estado        VARCHAR(20)  NOT NULL DEFAULT 'confirmada',
    -- Estados válidos: confirmada | anulada
    registrado_por UUID        NOT NULL REFERENCES auth.users(id)    ON DELETE RESTRICT,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    anulada_en    TIMESTAMPTZ,
    CONSTRAINT grupo_liquidaciones_distintos    CHECK (de_user_id <> para_user_id),
    CONSTRAINT grupo_liquidaciones_estado_chk  CHECK (estado IN ('confirmada','anulada'))
);
CREATE INDEX idx_grupo_liquidaciones_grupo ON grupo_liquidaciones(grupo_id);
CREATE INDEX idx_grupo_liquidaciones_de    ON grupo_liquidaciones(de_user_id);
CREATE INDEX idx_grupo_liquidaciones_para  ON grupo_liquidaciones(para_user_id);

-- ============================================================
-- SECCIÓN 2: FUNCIONES HELPER (SECURITY DEFINER STABLE)
-- Razón: policies inline con subqueries sobre grupo_miembros causan
-- recursión infinita cuando esa tabla tiene RLS. Con SECURITY DEFINER
-- los helpers bypassean RLS internamente y solo exponen BOOLEAN.
-- ============================================================

-- Verifica si un usuario es miembro activo de un grupo.
CREATE OR REPLACE FUNCTION is_group_member(p_grupo_id BIGINT, p_user_id UUID)
RETURNS BOOLEAN
LANGUAGE sql
SECURITY DEFINER
STABLE
AS $$
    SELECT EXISTS (
        SELECT 1 FROM grupo_miembros
        WHERE grupo_id = p_grupo_id
          AND user_id  = p_user_id
          AND estado   = 'activo'
    );
$$;

-- Verifica si un usuario es admin activo de un grupo.
CREATE OR REPLACE FUNCTION is_group_admin(p_grupo_id BIGINT, p_user_id UUID)
RETURNS BOOLEAN
LANGUAGE sql
SECURITY DEFINER
STABLE
AS $$
    SELECT EXISTS (
        SELECT 1 FROM grupo_miembros
        WHERE grupo_id = p_grupo_id
          AND user_id  = p_user_id
          AND estado   = 'activo'
          AND rol      = 'admin'
    );
$$;

-- Verifica si un usuario es el creador original del grupo.
CREATE OR REPLACE FUNCTION is_group_creator(p_grupo_id BIGINT, p_user_id UUID)
RETURNS BOOLEAN
LANGUAGE sql
SECURITY DEFINER
STABLE
AS $$
    SELECT EXISTS (
        SELECT 1 FROM grupos_gastos
        WHERE id = p_grupo_id
          AND creado_por = p_user_id
    );
$$;

-- Revocar acceso público y otorgar solo a usuarios autenticados.
-- Esto evita que el rol anon pueda invocar los helpers desde el cliente.
REVOKE ALL ON FUNCTION is_group_member(BIGINT, UUID) FROM PUBLIC;
REVOKE ALL ON FUNCTION is_group_admin (BIGINT, UUID) FROM PUBLIC;
REVOKE ALL ON FUNCTION is_group_creator(BIGINT, UUID) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION is_group_member(BIGINT, UUID) TO authenticated;
GRANT EXECUTE ON FUNCTION is_group_admin (BIGINT, UUID) TO authenticated;
GRANT EXECUTE ON FUNCTION is_group_creator(BIGINT, UUID) TO authenticated;

-- ============================================================
-- SECCIÓN 3: TRIGGERS
-- ============================================================

-- Trigger 3.1: Actualizar fecha_actualizacion en grupos_gastos al hacer UPDATE.
CREATE OR REPLACE FUNCTION grupos_set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.fecha_actualizacion = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_grupos_gastos_updated_at
    BEFORE UPDATE ON grupos_gastos
    FOR EACH ROW EXECUTE FUNCTION grupos_set_updated_at();

-- Trigger 3.2: Al crear un grupo, insertar al creador como admin activo.
-- Garantía atómica: el creador siempre es miembro/admin desde la primera fila,
-- sin race condition con RLS.
CREATE OR REPLACE FUNCTION grupos_alta_admin_creador()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO grupo_miembros (grupo_id, user_id, rol, estado)
    VALUES (NEW.id, NEW.creado_por, 'admin', 'activo');
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE TRIGGER trg_grupos_alta_admin
    AFTER INSERT ON grupos_gastos
    FOR EACH ROW EXECUTE FUNCTION grupos_alta_admin_creador();

